"""Rebuild the mobile PDF pages after replacing a document in pdfs/.

Requires Poppler (pdfinfo, pdftoppm) on PATH and Pillow for WebP output.
Run from any directory: python scripts/build-pdf-previews.py
The original PDFs are only read.
"""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
DOCUMENTS = {
    "mechnow": "MechNow.pdf",
    "plant-bud": "plant-bud.pdf",
    "social-service": "social-service.pdf",
    "excel-expert": "Microsoft Excel Expert Microsoft 365 Apps.pdf",
    "excel": "Microsoft Excel Microsoft 365 Apps.pdf",
}


def main():
    manifest = {}
    temporary_root = ROOT / "tmp" / "pdfs"
    temporary_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="mobile-preview-", dir=temporary_root) as temporary:
        assert Path(temporary).resolve().is_relative_to(ROOT)
        for identifier, filename in DOCUMENTS.items():
            source = ROOT / "pdfs" / filename
            information = subprocess.run(
                ["pdfinfo", str(source)], check=True, capture_output=True,
                text=True, encoding="utf-8", errors="replace",
            ).stdout
            count = int(re.search(r"^Pages:\s+(\d+)", information, re.MULTILINE)[1])
            target = ROOT / "assets" / "documents" / identifier
            target.mkdir(parents=True, exist_ok=True)
            pages = []
            for number in range(1, count + 1):
                prefix = Path(temporary) / f"{identifier}-{number:02}"
                subprocess.run([
                    "pdftoppm", "-f", str(number), "-singlefile", "-png",
                    "-scale-to-x", "1800", "-scale-to-y", "-1",
                    str(source), str(prefix),
                ], check=True, capture_output=True)
                image_path = target / f"{number:02}.webp"
                with Image.open(prefix.with_suffix(".png")) as image:
                    image.convert("RGB").save(image_path, "WEBP", quality=86, method=6)
                    pages.append({
                        "src": image_path.relative_to(ROOT).as_posix(),
                        "width": image.width, "height": image.height,
                    })
                prefix.with_suffix(".png").unlink()
            manifest[filename] = {
                "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                "pages": pages,
            }
            print(f"{filename}: {count} pages")
    (ROOT / "scripts" / "pdf-pages.js").write_text(
        "/* Generated by scripts/build-pdf-previews.py; original documents remain in pdfs/. */\n"
        "window.portfolioPdfPages = " + json.dumps(manifest, indent=2) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
